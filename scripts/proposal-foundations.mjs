import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const data=JSON.parse(readFileSync(new URL('../data/proposal-foundations.json',import.meta.url),'utf8'));
export const foundationTokens=Object.fromEntries(data.groups.flatMap(g=>g.tokens.map(t=>[t.name,t.value])));
const css='@import "./foundation-utilities.css";\n/* Generated by scripts/proposal-foundations.mjs. Edit data/proposal-foundations.json. */\n:root {\n'+Object.entries(foundationTokens).map(([name,value])=>`  --lab-ds-${name}: ${value};`).join('\n')+'\n}\n';
const target=new URL('../proposals/shared/foundations.css',import.meta.url);
if(process.argv[1]===fileURLToPath(import.meta.url)){
 if(process.argv.includes('--check')) {if(readFileSync(target,'utf8')!==css)throw Error('Fondamentaux CSS désynchronisés : exécuter npm run foundations:generate'); console.log(`${Object.keys(foundationTokens).length} jetons de propositions synchronisés.`);}
 else writeFileSync(target,css);
}
